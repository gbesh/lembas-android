"""Makes the bolder (gb_*) and two-tone (gd_*) drawings of the line-art glyphs (g_*) for the
Red Book's modern icon styles. Run after adding or changing a glyph:  python3 tools/glyph_variants.py"""
import glob, os, re
D = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
for f in sorted(glob.glob(os.path.join(D, "g_*.xml"))):
    s = open(f).read()
    bold = re.sub(r'android:strokeWidth="[\d.]+"', 'android:strokeWidth="1.9"', s)
    # two-tone: the inside of each line drawing gets a light fill (30%, tinted with the glyph)
    duo = bold.replace('android:fillColor="#00000000"', 'android:fillColor="#4DFFFFFF"')
    name = os.path.basename(f)[2:]
    for prefix, text in (("gb_", bold), ("gd_", duo)):
        open(os.path.join(D, prefix + name), "w").write(
            "<!-- generated by tools/glyph_variants.py from g_" + name + " -->\n" + text if not text.startswith("<?xml") else text)
